"""Initialize PostgreSQL and import the previous Docker SQLite inventory once."""
import sqlite3
from app import DATA, database

def initialize():
    with database() as db:
        db.execute('SELECT pg_advisory_xact_lock(728451)')
        db.execute('''CREATE TABLE IF NOT EXISTS pcs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            row_number INTEGER NOT NULL CHECK (row_number BETWEEN 1 AND 9999),
            column_number INTEGER NOT NULL CHECK (column_number BETWEEN 1 AND 9999),
            pc_type TEXT NOT NULL CHECK (pc_type IN ('MiniPC', 'Laptop')),
            photo TEXT NOT NULL
        )''')
        db.execute('CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY)')
        db.execute("ALTER TABLE pcs ADD COLUMN IF NOT EXISTS ocr_text TEXT NOT NULL DEFAULT ''")
        db.execute("ALTER TABLE pcs ADD COLUMN IF NOT EXISTS ocr_status TEXT NOT NULL DEFAULT 'pending'")
        db.execute("ALTER TABLE pcs ADD COLUMN IF NOT EXISTS ocr_confidence DOUBLE PRECISION")
        db.execute("ALTER TABLE pcs ADD COLUMN IF NOT EXISTS ocr_lines JSONB NOT NULL DEFAULT '[]'::jsonb")
        db.execute("ALTER TABLE pcs ADD COLUMN IF NOT EXISTS ocr_attempts INTEGER NOT NULL DEFAULT 0")
        if not db.execute("SELECT name FROM schema_migrations WHERE name='ocr-confidence'").fetchone():
            db.execute("UPDATE pcs SET ocr_status='pending', ocr_attempts=0")
            db.execute("INSERT INTO schema_migrations (name) VALUES ('ocr-confidence')")
        db.execute("ALTER TABLE pcs ADD COLUMN IF NOT EXISTS ocr_duration_seconds DOUBLE PRECISION")
        migrated = db.execute("SELECT name FROM schema_migrations WHERE name='sqlite-import'").fetchone()
        legacy = DATA / 'shelf.sqlite3'
        if legacy.exists() and not migrated:
            if db.execute('SELECT COUNT(*) AS count FROM pcs').fetchone()['count']:
                raise RuntimeError('PostgreSQL already has records; refusing to merge the legacy SQLite inventory automatically.')
            connection = sqlite3.connect(f'{legacy.as_uri()}?mode=ro', uri=True)
            try:
                records = connection.execute('SELECT id, row_number, column_number, pc_type, photo FROM pcs').fetchall()
            finally:
                connection.close()
            for record in records:
                db.execute('INSERT INTO pcs (id, row_number, column_number, pc_type, photo) VALUES (%s, %s, %s, %s, %s)', record)
            db.execute("SELECT setval(pg_get_serial_sequence('pcs', 'id'), COALESCE(MAX(id), 1), COUNT(*) > 0) FROM pcs")
            db.execute("INSERT INTO schema_migrations (name) VALUES ('sqlite-import')")
            print(f'Imported {len(records)} existing PC records into PostgreSQL.')

if __name__ == '__main__':
    initialize()
